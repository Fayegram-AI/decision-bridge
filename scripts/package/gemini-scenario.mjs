/** Installed Gemini native/common media, CLI and declaration verification. */
export function geminiScenario(name) {
    return [
        "import assert from 'node:assert/strict';",
        "import { spawnSync } from 'node:child_process';",
        "import { fileURLToPath } from 'node:url';",
        'import { GeminiDecisionsProvider, createBridge, createProvider, validateRequest } from ' + JSON.stringify(name) + ';',
        "process.env.DECISION_BRIDGE_GEMINI_API_KEY = 'environment-fixture';",
        "process.env.GEMINI_API_KEY = 'other-fixture';",
        'const environmentProvider = new GeminiDecisionsProvider({fetchImpl:async(_url,init)=>{',
        '    assert.equal(init.headers["x-goog-api-key"],"environment-fixture");',
        '    return Response.json({name:"models/gemini-decision-1"});',
        '}});',
        'await environmentProvider.listModels();',
        'delete process.env.DECISION_BRIDGE_GEMINI_API_KEY;',
        'await new GeminiDecisionsProvider({fetchImpl:async(_url,init)=>{',
        '    assert.equal(init.headers["x-goog-api-key"],"other-fixture");',
        '    return Response.json({name:"models/gemini-decision-1"});',
        '}}).listModels();',
        'delete process.env.GEMINI_API_KEY;',
        'let calls = 0;',
        "const provider = new GeminiDecisionsProvider({ apiKey: 'fixture', fetchImpl: async (url, init) => {",
        '    calls++;',
        "    assert.equal(init.headers['x-goog-api-key'], 'fixture');",
        "    if (init.method === 'GET') return Response.json({ name: 'models/gemini-decision-1' });",
        '    const body = JSON.parse(init.body);',
        "    assert.equal(url, 'https://generativelanguage.googleapis.com/v1beta/decisions');",
        "    return Response.json({ answers: Object.fromEntries(Object.keys(body.questions).map(id => [id, {type:'noul',noul:0.8,confidence:0.8}])),",
        '        usage: {total_input_tokens:3,total_output_tokens:0} });',
        '} });',
        "const questions = { yes: { type: 'noul', instructions: 'Present?' } };",
        'let inheritedNodePolicyReads = 0;',
        'Object.defineProperty(Object.prototype,"maxJsonNodes",{configurable:true,get(){inheritedNodePolicyReads++;return 1;}});',
        'try { validateRequest({state:"x",questions},"gemini-decision-1");assert.equal(inheritedNodePolicyReads,0); }',
        'finally { delete Object.prototype.maxJsonNodes; }',
        "const input = [{ type:'document',url:'https://example.com/a.pdf' }, { type:'audio',url:'https://example.com/a.ogg',mimeType:'audio/ogg' }];",
        'const common = await createBridge({provider}).evaluate({input,questions});',
        'assert.equal(common.meta.schemaVersion,7);',
        "assert.equal(common.meta.modelSource,'requested');",
        'assert.equal(common.meta.geminiDecisions.answers.yes.confidence,0.8);',
        'assert.equal(provider.getCapabilities().maxJsonNodes,1000000);',
        'assert.deepEqual(provider.getCapabilities().videoResolutions,["low","medium","high"]);',
        'const resolved = await createBridge({provider}).evaluate({input:[{type:"image",url:"https://example.com/a.png",mimeType:"image/png",resolution:"ultra_high"}],questions});',
        'assert.equal(resolved.meta.schemaVersion,8);',
        'new GeminiDecisionsProvider({apiKey:"fixture",maxRequestBytes:167772160});',
        "assert.equal((await provider.listModels()).models[0].name,'gemini-decision-1');",
        "const native = {input:{type:'document',uri:'https://example.com/a.pdf',mime_type:'application/pdf'},questions};",
        'assert.equal((await provider.createDecision(native)).decision.answers.yes.confidence,0.8);',
        'const callsBeforeInvalidKey = calls;',
        'await assert.rejects(provider.createDecision({input:"Text",questions:{q:{type:"choice",instructions:"Pick",criteria:{"a\\u200Db":"",ok:""}}}}),{code:"VALIDATION_ERROR"});',
        'assert.equal(calls,callsBeforeInvalidKey);',
        'const blocked = new GeminiDecisionsProvider({apiKey:"fixture",fetchImpl:async()=>Response.json({error:{code:"safety"}},{status:400})});',
        'await assert.rejects(blocked.createDecision(native),error=>{',
        '    const details=error.toJSON();',
        '    assert.equal(details.upstreamErrorCode,"safety");assert.equal(details.upstreamCode,undefined);return true;',
        '});',
        "assert(createProvider({type:'gemini-decisions',apiKey:'fixture'}) instanceof GeminiDecisionsProvider);",
        "const cli = fileURLToPath(new URL('../bin/decision.mjs',import.meta.resolve(" + JSON.stringify(name) + ')));',
        'for (const [request,flags] of [[{input,questions},[]],[native,["--native"]]]) {',
        '    const result = spawnSync(process.execPath,[cli,"validate","-","--provider","gemini-decisions",...flags],',
        '        {input:JSON.stringify(request),encoding:"utf8"});',
        '    assert.equal(result.status,0,result.stderr);',
        '    assert.equal(JSON.parse(result.stdout).model,"gemini-decision-1");',
        '}',
        "console.log('Installed Gemini native/common media, metadata and offline CLI checks passed.');",
    ].join('\n') + '\n';
}

export function geminiTypes(name) {
    return [
        'import { GeminiDecisionsProvider as InstalledGemini, type GeminiDecisionRequest as InstalledGeminiRequest, validateRequest as installedValidateGoogleRequest, type ResolvedRequest as InstalledGoogleResolvedRequest } from ' + JSON.stringify(name) + ';',
        'const installedGoogle = new InstalledGemini({apiKey:"fixture"});',
        'const installedGoogleRequest: InstalledGeminiRequest = {input:{type:"document",uri:"https://example.com/a.pdf",mime_type:"application/pdf"},',
        '    questions:{yes:{type:"noul",instructions:"Present?"}}};',
        'await installedGoogle.createDecision(installedGoogleRequest);',
        'const installedGoogleChoice = await installedGoogle.createDecision({input:"Text",questions:{pick:{type:"choice",instructions:"Pick",criteria:{a:"",b:""}}}});',
        'const installedGoogleValue: "a"|"b" = installedGoogleChoice.decision.answers.pick.choice;',
        'void installedGoogleValue;',
        'const installedGoogleNumeric = await installedGoogle.createDecision({input:"Text",questions:{pick:{type:"choice",instructions:"Pick",criteria:{0:"zero",fallback:"other"}}}});',
        'const installedNumericValue: "0"|"fallback" = installedGoogleNumeric.decision.answers.pick.choice;',
        'const installedZero: typeof installedGoogleNumeric.decision.answers.pick.choice = "0";',
        'const installedNumericProbability: number = installedGoogleNumeric.decision.answers.pick.probabilities["0"];',
        'void [installedNumericValue,installedZero,installedNumericProbability];',
        'const installedValidationQuestions = {pick:{type:"choice",instructions:"Pick",criteria:{a:"First",b:"Second"}}} as const;',
        'const installedValidatedGoogle = installedValidateGoogleRequest({state:"x",questions:installedValidationQuestions},"gemini-decision-1",{maxJsonNodes:1000000});',
        'const installedValidatedGoogleTyped: InstalledGoogleResolvedRequest<typeof installedValidationQuestions> = installedValidatedGoogle;',
        'void installedValidatedGoogleTyped;',
        'await installedGoogle.evaluate({input:[{type:"video",url:"https://example.com/a.mp4",mimeType:"video/mp4",resolution:"medium"}],questions:{q:{type:"noul",instructions:"Visible?"}}});',
    ].join('\n') + '\n';
}
